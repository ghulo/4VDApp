export type PixelArtName = keyof typeof PIXEL_ART;

/** The filled blocks of a drawing as grid cells. */
export function pixelCells(name: PixelArtName): Array<{ x: number; y: number }> {
  return PIXEL_ART[name].flatMap((row, y) => [...row].flatMap((cell, x) => (cell === '#' ? [{ x, y }] : [])));
}
